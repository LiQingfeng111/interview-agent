def main() -> int:
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    seen = set()
    rows = []
    for rid, split, topic, label, q, a in ITEMS:
        if rid in seen:
            raise SystemExit(f"id 重复：{rid}")
        seen.add(rid)
        rows.append({"id": rid, "split": split, "topic": topic,
                     "label": label, "question": q, "answer": a})

    with open(OUT, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    from collections import Counter
    print(f"已写 {len(rows)} 条 → {OUT}")
    for split in ("train", "holdout"):
        sub = [r for r in rows if r["split"] == split]
        dist = Counter(r["label"] for r in sub)
        topics = Counter(r["topic"] for r in sub)
        print(f"  {split:<8} {len(sub):>3} 条 · 标签 {dict(dist)} · 方向 {dict(topics)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
